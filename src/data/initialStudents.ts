// SVG Avatar generator for fallback or clean student portraits
export function getStudentAvatar(name: string, gender: 'boy' | 'girl', index: number): string {
  const boyBg = ['#0284c7', '#0d9488', '#2563eb', '#4f46e5', '#16a34a'];
  const girlBg = ['#e11d48', '#d946ef', '#db2777', '#9333ea', '#ea580c'];
  const bg = gender === 'boy' ? boyBg[index % boyBg.length] : girlBg[index % girlBg.length];

  const firstLetter = name.trim().charAt(0) || (gender === 'boy' ? 'ક' : 'ક');

  return `data:image/svg+xml;utf8,<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120" width="120" height="120">
    <rect width="120" height="120" rx="28" fill="${encodeURIComponent(bg)}"/>
    <circle cx="60" cy="46" r="22" fill="white" fill-opacity="0.95"/>
    <path d="M24 104 C24 82, 42 74, 60 74 C78 74, 96 82, 96 104 Z" fill="white" fill-opacity="0.95"/>
    <text x="60" y="53" font-size="20" font-family="'Noto Sans Gujarati', sans-serif" font-weight="bold" fill="${encodeURIComponent(
      bg
    )}" text-anchor="middle">${encodeURIComponent(firstLetter)}</text>
  </svg>`;
}

